"""
Tests of loading SARA's cases, the facts their rules generate included.
"""

from __future__ import annotations

from law_as_code_benchmarks.sara.case import SaraCase, SaraSplit
from law_as_code_benchmarks.sara.case_reader import WorldReader
from law_as_code_benchmarks.sara.prolog_term import CompoundTerm

# %% splits


def test_the_published_splits_hold_376_cases() -> None:
    """
    The splits list SARA's 256 training and 120 test cases.
    """
    assert len(SaraSplit.TRAIN.case_identifiers()) == 256
    assert len(SaraSplit.TEST.case_identifiers()) == 120


# %% test goals


def test_a_negated_test_is_expected_to_fail(swipl: str) -> None:
    """
    A test directive negated with ``\\+`` expects its goal to have no solution.
    """
    case = SaraCase.load("s3306_c_6_neg", swipl)
    assert case.test.goal == CompoundTerm(
        functor="s3306_c_6", arguments=("alice_employed",)
    )
    assert not case.test.expected_to_hold


def test_a_last_fact_without_a_full_stop_does_not_swallow_the_test(swipl: str) -> None:
    """
    A last fact missing its full stop leaves the test directive a test.
    """
    case = SaraCase.load("s3306_c_2_pos", swipl)
    assert case.test.goal == CompoundTerm(
        functor="s3306_c_2", arguments=("alice_employer", None, 2017)
    )
    assert case.test.expected_to_hold


# %% facts generated by rules


def test_rules_naming_their_events_are_expanded_for_every_event(swipl: str) -> None:
    """
    Role clauses that need their event's name bound are solved for every event the case
    names.
    """
    world = WorldReader.from_facts(SaraCase.load("tax_case_33", swipl).facts).read()
    assert len(world.services) == 87 + 70
    assert {service.employer.name for service in world.services} == {"alice"}
